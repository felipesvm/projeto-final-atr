// Exercita, por MQTT, os comandos da tela e do simulador e confere o efeito no estado publicado.
import mqtt from 'mqtt';
const c = mqtt.connect(process.argv[2] ?? 'mqtt://127.0.0.1:1883');
let sup, sim;
const eventos = [];
c.on('connect', () => c.subscribe(['amr/sup/estado', 'amr/sim/estado', 'amr/log/evento', 'amr/sup/alarme']));
c.on('message', (t, d) => {
  const m = JSON.parse(d);
  if (t === 'amr/sup/estado') sup = m;
  else if (t === 'amr/sim/estado') sim = m;
  else eventos.push(m.texto);
});
const esperar = (ms) => new Promise((r) => setTimeout(r, ms));
const op = (acao, x = {}) => c.publish('amr/cmd/operador', JSON.stringify({ acao, ...x }), { qos: 1 });
const simc = (acao, x = {}) => c.publish('amr/sim/cmd', JSON.stringify({ acao, ...x }), { qos: 1 });
const robo = (id) => sup.robos.find((r) => r.id === id);
const fis = (id) => sim.robos.find((r) => r.id === id);
const resultados = [];
const conferir = (nome, ok, detalhe = '') => { resultados.push([nome, ok]); console.log(`${ok ? 'OK   ' : 'FALHA'} ${nome}${detalhe ? ` — ${detalhe}` : ''}`); };

await esperar(3000);
const id = sup.robos[0].id;
op('modo', { robo: id, modo: 'manual' });
await esperar(1500);
conferir('modo manual pela tela', robo(id).modo === 'MANUAL');
for (let i = 0; i < 30 && robo(id).estado !== 'DISPONIVEL'; i++) await esperar(500);
conferir('missão em andamento é abortada ao passar para manual', robo(id).estado === 'DISPONIVEL' && robo(id).caixa < 0, robo(id).estado);
op('destino', { robo: id, x: 10.5, y: 10.5 });
await esperar(800);
conferir('destino arbitrário aceito', ['DESLOCANDO', 'AGUARDANDO_PASSAGEM'].includes(robo(id).estado) || Math.hypot(fis(id).x - 10.5, fis(id).y - 10.5) < 0.5, robo(id).estado);
for (let i = 0; i < 80 && Math.hypot(fis(id).x - 10.5, fis(id).y - 10.5) > 0.3; i++) await esperar(500);
conferir('robô chegou ao destino manual', Math.hypot(fis(id).x - 10.5, fis(id).y - 10.5) < 0.3, `(${fis(id).x}, ${fis(id).y})`);
op('destino', { robo: id, local: { tipo: 'recarga', id: 0 } });
await esperar(1000);
op('parar', { robo: id });
await esperar(1000);
const p1 = { ...fis(id) };
await esperar(1500);
conferir('PARAR congela o robô', Math.hypot(fis(id).x - p1.x, fis(id).y - p1.y) < 0.05 && robo(id).parado);
op('retomar', { robo: id });
await esperar(1500);
conferir('RETOMAR libera o movimento', fis(id).v > 0.05 || robo(id).estado !== 'DESLOCANDO', `v=${fis(id).v}`);
simc('defeito', { robo: id, ativo: true });
await esperar(800);
conferir('defeito gerado no simulador chega como DEFEITO', robo(id).estado === 'DEFEITO');
simc('defeito', { robo: id, ativo: false });
await esperar(500);
op('reconhecer', { robo: id });
await esperar(800);
conferir('reconhecer falha volta a DISPONIVEL', robo(id).estado === 'DISPONIVEL', robo(id).estado);
simc('bateria', { robo: id, nivel: 25 });
op('modo', { robo: id, modo: 'auto' });
for (let i = 0; i < 10 && !['DESLOCANDO_RECARGA', 'RECARREGANDO'].includes(robo(id).estado); i++) await esperar(500);
conferir('bateria baixa leva à recarga', ['DESLOCANDO_RECARGA', 'RECARREGANDO'].includes(robo(id).estado), robo(id).estado);
const antes = sup.robos.length;
simc('novo_robo');
for (let i = 0; i < 20 && sup.robos.length === antes; i++) await esperar(500);
conferir('novo robô do simulador vira processo', sup.robos.length === antes + 1, `${antes} -> ${sup.robos.length}`);
const caixas = sup.caixas.length;
simc('nova_caixa', { baia: 1, tamanho: 2, zona: 1 });
await esperar(1500);
conferir('caixa nova incluída pela simulação', sup.caixas.length === caixas + 1);
op('parada_geral');
await esperar(1000);
const fotos = sim.robos.map((r) => ({ ...r }));
await esperar(1500);
conferir('parada geral congela a frota', sup.sistema.parada_geral && sim.robos.every((r) => { const a = fotos.find((f) => f.id === r.id); return !a || Math.hypot(r.x - a.x, r.y - a.y) < 0.1; }));
op('liberar_parada');
await esperar(1000);
conferir('histórico do coletor chega à tela', eventos.length > 0, `${eventos.length} registros`);
console.log(`${resultados.filter((r) => r[1]).length}/${resultados.length} verificações`);
process.exit(resultados.every((r) => r[1]) ? 0 : 1);
